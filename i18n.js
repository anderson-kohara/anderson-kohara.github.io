function translate(source) {
  return translations[currentLanguage]?.[source] ?? source;
}

function translateStaticPage() {
  document.documentElement.lang = currentLanguage;
  document.title = translate(document.title);

  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = translate(description.content);

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest('script, style, svg, .publication-title, .publication-authors, .publication-journal, .cv-publication-details ol, [data-no-translate]')) continue;
    const source = node.nodeValue.trim();
    if (!source || translate(source) === source) continue;
    node.nodeValue = node.nodeValue.replace(source, translate(source));
  }

  for (const element of document.querySelectorAll('[placeholder], [aria-label], [alt]')) {
    for (const attribute of ['placeholder', 'aria-label', 'alt']) {
      if (element.hasAttribute(attribute)) element.setAttribute(attribute, translate(element.getAttribute(attribute)));
    }
  }

  for (const anchor of document.querySelectorAll('a[href]')) {
    const href = anchor.getAttribute('href');
    if (/^(index|cv|publications|teaching|booster-physique|mecanique-analytique|mecanique-analytique-calcul-variationnel|mecanique-analytique-coordonnees-generalisees)\.html(?:[?#]|$)/.test(href)) {
      const url = new URL(href, window.location.href);
      url.searchParams.set('lang', currentLanguage);
      anchor.href = url.href;
    }
  }

  const selector = document.querySelector('#language-select');
  if (selector) {
    selector.value = currentLanguage;
    selector.addEventListener('change', () => {
      const language = selector.value;
      try { localStorage.setItem('site-language', language); } catch { /* Storage can be unavailable. */ }
      const url = new URL(window.location.href);
      url.searchParams.set('lang', language);
      window.location.assign(url.href);
    });
  }
}

window.siteI18n = {
  language: currentLanguage,
  t: translate,
  publicationCount(shown, total) {
    if (currentLanguage === 'pt-BR') return `Exibindo ${shown} de ${total} publicações`;
    if (currentLanguage === 'fr') return `${shown} publications affichées sur ${total}`;
    return `Showing ${shown} of ${total} publications`;
  }
};

